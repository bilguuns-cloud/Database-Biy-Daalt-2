--  generate_series 
INSERT INTO Өргөдөл (зар_id, горилогч_id, тохирлын_хувь, үндсэн_төлөв, илгээсэн_огноо)
SELECT 
    ((i - 1) % 15) + 1 AS зар_id,
    ((i - 1) % 15) + 1 AS горилогч_id,
    ROUND((60 + (i * 7) % 39)::numeric, 2) AS тохирлын_хувь,
    CASE 
        WHEN i % 5 = 0 THEN 'Тэнцсэн'
        WHEN i % 5 = 1 THEN 'Илгээсэн'
        WHEN i % 5 = 2 THEN 'Шүүгдсэн'
        WHEN i % 5 = 3 THEN 'Ярилцлага'
        ELSE 'Тэнцээгүй'
    END AS үндсэн_төлөв,
    CURRENT_TIMESTAMP - (i || ' hours')::INTERVAL AS илгээсэн_огноо
FROM generate_series(1, 215) AS i
ON CONFLICT (зар_id, горилогч_id) DO NOTHING;